-- =============================================================
-- BeaconSync - schema inicial (Oracle 19c+ / 23ai)
-- Prefixo BS_ para não colidir com tabelas de outros projetos
-- no schema compartilhado do Oracle da FIAP.
-- Booleanos em NUMBER(1) (0/1) para funcionar no 19c e no 23ai.
-- =============================================================

-- Órgãos de resgate (Bombeiros, PM, Defesa Civil, SAMU, GCM)
CREATE TABLE BS_ORGAO (
                          id    NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                          nome  VARCHAR2(120 CHAR) NOT NULL,
                          tipo  VARCHAR2(20 CHAR)  NOT NULL,
                          CONSTRAINT PK_BS_ORGAO PRIMARY KEY (id),
                          CONSTRAINT UK_BS_ORGAO_NOME UNIQUE (nome),
                          CONSTRAINT CK_BS_ORGAO_TIPO CHECK (tipo IN ('BOMBEIROS', 'POLICIA_MILITAR', 'DEFESA_CIVIL', 'SAMU', 'GUARDA_MUNICIPAL'))
);

-- Usuários do sistema (responsáveis, voluntários, profissionais, agentes)
CREATE TABLE BS_USUARIO (
                            id          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                            nome        VARCHAR2(120 CHAR) NOT NULL,
                            email       VARCHAR2(160 CHAR) NOT NULL,
                            senha_hash  VARCHAR2(100 CHAR) NOT NULL,
                            telefone    VARCHAR2(20 CHAR),
                            papel       VARCHAR2(20 CHAR)  NOT NULL,
                            orgao_id    NUMBER(19),
                            ativo       NUMBER(1) DEFAULT 1 NOT NULL,
                            criado_em   TIMESTAMP NOT NULL,
                            CONSTRAINT PK_BS_USUARIO PRIMARY KEY (id),
                            CONSTRAINT UK_BS_USUARIO_EMAIL UNIQUE (email),
                            CONSTRAINT FK_BS_USUARIO_ORGAO FOREIGN KEY (orgao_id) REFERENCES BS_ORGAO (id),
                            CONSTRAINT CK_BS_USUARIO_PAPEL CHECK (papel IN ('RESPONSAVEL', 'VOLUNTARIO', 'PROFISSIONAL', 'AGENTE_ORGAO')),
                            CONSTRAINT CK_BS_USUARIO_ATIVO CHECK (ativo IN (0, 1)),
    -- Profissionais e agentes sempre pertencem a um órgão
                            CONSTRAINT CK_BS_USUARIO_ORGAO CHECK (papel NOT IN ('PROFISSIONAL', 'AGENTE_ORGAO') OR orgao_id IS NOT NULL)
);

-- 96 distritos oficiais de São Paulo (carga na V2)
CREATE TABLE BS_DISTRITO (
                             id             NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                             codigo         NUMBER(3)         NOT NULL,
                             nome           VARCHAR2(60 CHAR) NOT NULL,
                             subprefeitura  VARCHAR2(60 CHAR) NOT NULL,
                             CONSTRAINT PK_BS_DISTRITO PRIMARY KEY (id),
                             CONSTRAINT UK_BS_DISTRITO_CODIGO UNIQUE (codigo),
                             CONSTRAINT UK_BS_DISTRITO_NOME UNIQUE (nome)
);

-- Pessoa vulnerável: um único registro por CPF
CREATE TABLE BS_PESSOA_VULNERAVEL (
                                      id                    NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                      nome                  VARCHAR2(120 CHAR) NOT NULL,
                                      data_nascimento       DATE               NOT NULL,
                                      cpf                   VARCHAR2(11 CHAR)  NOT NULL,
                                      tipo_vulnerabilidade  VARCHAR2(30 CHAR)  NOT NULL,
                                      necessidades_remocao  VARCHAR2(500 CHAR),
                                      consentimento_em      TIMESTAMP          NOT NULL,
                                      endereco_atual_id     NUMBER(19),
                                      criado_em             TIMESTAMP          NOT NULL,
                                      atualizado_em         TIMESTAMP,
                                      CONSTRAINT PK_BS_PESSOA PRIMARY KEY (id),
                                      CONSTRAINT UK_BS_PESSOA_CPF UNIQUE (cpf),
                                      CONSTRAINT CK_BS_PESSOA_TIPO CHECK (tipo_vulnerabilidade IN ('ACAMADO', 'PESSOA_COM_DEFICIENCIA', 'BEBE', 'DEPENDENTE_APARELHO_MEDICO', 'OUTRO'))
);

-- Endereços da pessoa (casa, casa da filha, centro-dia...)
CREATE TABLE BS_ENDERECO (
                             id           NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                             pessoa_id    NUMBER(19)         NOT NULL,
                             distrito_id  NUMBER(19)         NOT NULL,
                             apelido      VARCHAR2(60 CHAR)  NOT NULL,
                             logradouro   VARCHAR2(150 CHAR) NOT NULL,
                             numero       VARCHAR2(10 CHAR)  NOT NULL,
                             complemento  VARCHAR2(60 CHAR),
                             cep          VARCHAR2(8 CHAR)   NOT NULL,
                             CONSTRAINT PK_BS_ENDERECO PRIMARY KEY (id),
                             CONSTRAINT FK_BS_ENDERECO_PESSOA FOREIGN KEY (pessoa_id) REFERENCES BS_PESSOA_VULNERAVEL (id) ON DELETE CASCADE,
                             CONSTRAINT FK_BS_ENDERECO_DISTRITO FOREIGN KEY (distrito_id) REFERENCES BS_DISTRITO (id)
);

-- Endereço atual: FK criada depois por causa da referência circular
ALTER TABLE BS_PESSOA_VULNERAVEL ADD CONSTRAINT FK_BS_PESSOA_END_ATUAL
    FOREIGN KEY (endereco_atual_id) REFERENCES BS_ENDERECO (id);

-- Vínculo responsável x pessoa (N:N com atributos)
CREATE TABLE BS_VINCULO_RESPONSAVEL (
                                        id          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                        pessoa_id   NUMBER(19)        NOT NULL,
                                        usuario_id  NUMBER(19)        NOT NULL,
                                        parentesco  VARCHAR2(40 CHAR) NOT NULL,
                                        status      VARCHAR2(10 CHAR) NOT NULL,
                                        criado_em   TIMESTAMP         NOT NULL,
                                        CONSTRAINT PK_BS_VINCULO PRIMARY KEY (id),
                                        CONSTRAINT UK_BS_VINCULO UNIQUE (pessoa_id, usuario_id),
                                        CONSTRAINT FK_BS_VINCULO_PESSOA FOREIGN KEY (pessoa_id) REFERENCES BS_PESSOA_VULNERAVEL (id) ON DELETE CASCADE,
                                        CONSTRAINT FK_BS_VINCULO_USUARIO FOREIGN KEY (usuario_id) REFERENCES BS_USUARIO (id),
                                        CONSTRAINT CK_BS_VINCULO_STATUS CHECK (status IN ('PENDENTE', 'ATIVO', 'RECUSADO'))
);

-- Alerta emitido por um órgão para uma lista de distritos
CREATE TABLE BS_ALERTA (
                           id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                           orgao_id        NUMBER(19)          NOT NULL,
                           emitido_por_id  NUMBER(19)          NOT NULL,
                           titulo          VARCHAR2(120 CHAR)  NOT NULL,
                           descricao       VARCHAR2(1000 CHAR),
                           status          VARCHAR2(10 CHAR)   NOT NULL,
                           emitido_em      TIMESTAMP           NOT NULL,
                           encerrado_em    TIMESTAMP,
                           CONSTRAINT PK_BS_ALERTA PRIMARY KEY (id),
                           CONSTRAINT FK_BS_ALERTA_ORGAO FOREIGN KEY (orgao_id) REFERENCES BS_ORGAO (id),
                           CONSTRAINT FK_BS_ALERTA_EMISSOR FOREIGN KEY (emitido_por_id) REFERENCES BS_USUARIO (id),
                           CONSTRAINT CK_BS_ALERTA_STATUS CHECK (status IN ('ATIVO', 'ENCERRADO'))
);

CREATE TABLE BS_ALERTA_DISTRITO (
                                    alerta_id    NUMBER(19) NOT NULL,
                                    distrito_id  NUMBER(19) NOT NULL,
                                    CONSTRAINT PK_BS_ALERTA_DISTRITO PRIMARY KEY (alerta_id, distrito_id),
                                    CONSTRAINT FK_BS_AD_ALERTA FOREIGN KEY (alerta_id) REFERENCES BS_ALERTA (id) ON DELETE CASCADE,
                                    CONSTRAINT FK_BS_AD_DISTRITO FOREIGN KEY (distrito_id) REFERENCES BS_DISTRITO (id)
);

-- Situação de cada pessoa em cada alerta: uma linha por (alerta, pessoa)
CREATE TABLE BS_SITUACAO_ALERTA (
                                    id                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                    alerta_id          NUMBER(19)          NOT NULL,
                                    pessoa_id          NUMBER(19)          NOT NULL,
                                    endereco_id        NUMBER(19)          NOT NULL,
                                    situacao           VARCHAR2(20 CHAR)   NOT NULL,
                                    descricao_livre    VARCHAR2(2000 CHAR),
                                    respondido_por_id  NUMBER(19),
                                    respondido_em      TIMESTAMP,
    -- Resultado da triagem (IA ou regra base)
                                    gravidade          NUMBER(1),
                                    risco_imediato     NUMBER(1),
                                    necessidades       VARCHAR2(500 CHAR),
                                    resumo_equipe      VARCHAR2(1000 CHAR),
                                    origem_triagem     VARCHAR2(10 CHAR),
                                    triado_em          TIMESTAMP,
                                    criado_em          TIMESTAMP           NOT NULL,
                                    versao             NUMBER(10) DEFAULT 0 NOT NULL,
                                    CONSTRAINT PK_BS_SITUACAO PRIMARY KEY (id),
                                    CONSTRAINT UK_BS_SITUACAO UNIQUE (alerta_id, pessoa_id),
                                    CONSTRAINT FK_BS_SITUACAO_ALERTA FOREIGN KEY (alerta_id) REFERENCES BS_ALERTA (id) ON DELETE CASCADE,
                                    CONSTRAINT FK_BS_SITUACAO_PESSOA FOREIGN KEY (pessoa_id) REFERENCES BS_PESSOA_VULNERAVEL (id) ON DELETE CASCADE,
                                    CONSTRAINT FK_BS_SITUACAO_ENDERECO FOREIGN KEY (endereco_id) REFERENCES BS_ENDERECO (id),
                                    CONSTRAINT FK_BS_SITUACAO_RESPONDEU FOREIGN KEY (respondido_por_id) REFERENCES BS_USUARIO (id),
                                    CONSTRAINT CK_BS_SITUACAO CHECK (situacao IN ('PENDENTE', 'SEGURA', 'PRECISA_AJUDA', 'SEM_CONTATO', 'RESGATADA')),
                                    CONSTRAINT CK_BS_SITUACAO_GRAV CHECK (gravidade IS NULL OR gravidade BETWEEN 1 AND 5),
                                    CONSTRAINT CK_BS_SITUACAO_RISCO CHECK (risco_imediato IS NULL OR risco_imediato IN (0, 1)),
                                    CONSTRAINT CK_BS_SITUACAO_ORIGEM CHECK (origem_triagem IS NULL OR origem_triagem IN ('IA', 'REGRA'))
);

-- Ocorrência de resgate (nasce de um pedido de ajuda)
CREATE TABLE BS_OCORRENCIA (
                               id                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                               situacao_id        NUMBER(19)        NOT NULL,
                               orgao_id           NUMBER(19)        NOT NULL,
                               status             VARCHAR2(15 CHAR) NOT NULL,
                               score_prioridade   NUMBER(5,2) DEFAULT 0 NOT NULL,
                               prioridade_manual  NUMBER(5),
                               criada_em          TIMESTAMP         NOT NULL,
                               concluida_em       TIMESTAMP,
                               CONSTRAINT PK_BS_OCORRENCIA PRIMARY KEY (id),
                               CONSTRAINT UK_BS_OCORRENCIA_SITUACAO UNIQUE (situacao_id),
                               CONSTRAINT FK_BS_OCORRENCIA_SITUACAO FOREIGN KEY (situacao_id) REFERENCES BS_SITUACAO_ALERTA (id) ON DELETE CASCADE,
                               CONSTRAINT FK_BS_OCORRENCIA_ORGAO FOREIGN KEY (orgao_id) REFERENCES BS_ORGAO (id),
                               CONSTRAINT CK_BS_OCORRENCIA_STATUS CHECK (status IN ('SOLICITADA', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA'))
);

-- Histórico de cada mudança de etapa
CREATE TABLE BS_HISTORICO_OCORRENCIA (
                                         id               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                         ocorrencia_id    NUMBER(19)        NOT NULL,
                                         status_anterior  VARCHAR2(15 CHAR),
                                         status_novo      VARCHAR2(15 CHAR) NOT NULL,
                                         alterado_por_id  NUMBER(19),
                                         alterado_em      TIMESTAMP         NOT NULL,
                                         observacao       VARCHAR2(500 CHAR),
                                         CONSTRAINT PK_BS_HISTORICO PRIMARY KEY (id),
                                         CONSTRAINT FK_BS_HISTORICO_OCORRENCIA FOREIGN KEY (ocorrencia_id) REFERENCES BS_OCORRENCIA (id) ON DELETE CASCADE,
                                         CONSTRAINT FK_BS_HISTORICO_USUARIO FOREIGN KEY (alterado_por_id) REFERENCES BS_USUARIO (id)
);

-- Perfil de resgatista (profissional ou voluntário) de um usuário
CREATE TABLE BS_RESGATISTA (
                               id                NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                               usuario_id        NUMBER(19)         NOT NULL,
                               tipo              VARCHAR2(15 CHAR)  NOT NULL,
                               habilidades       VARCHAR2(300 CHAR),
                               disponivel        NUMBER(1) DEFAULT 0 NOT NULL,
                               orgao_id          NUMBER(19),
                               distrito_base_id  NUMBER(19),
                               CONSTRAINT PK_BS_RESGATISTA PRIMARY KEY (id),
                               CONSTRAINT UK_BS_RESGATISTA_USUARIO UNIQUE (usuario_id),
                               CONSTRAINT FK_BS_RESGATISTA_USUARIO FOREIGN KEY (usuario_id) REFERENCES BS_USUARIO (id),
                               CONSTRAINT FK_BS_RESGATISTA_ORGAO FOREIGN KEY (orgao_id) REFERENCES BS_ORGAO (id),
                               CONSTRAINT FK_BS_RESGATISTA_DISTRITO FOREIGN KEY (distrito_base_id) REFERENCES BS_DISTRITO (id),
                               CONSTRAINT CK_BS_RESGATISTA_TIPO CHECK (tipo IN ('PROFISSIONAL', 'VOLUNTARIO')),
                               CONSTRAINT CK_BS_RESGATISTA_DISP CHECK (disponivel IN (0, 1))
);

-- Equipe de cada resgate (N:N com atributos)
CREATE TABLE BS_PARTICIPACAO_RESGATE (
                                         id             NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                         ocorrencia_id  NUMBER(19)        NOT NULL,
                                         resgatista_id  NUMBER(19)        NOT NULL,
                                         funcao         VARCHAR2(60 CHAR),
                                         entrou_em      TIMESTAMP         NOT NULL,
                                         CONSTRAINT PK_BS_PARTICIPACAO PRIMARY KEY (id),
                                         CONSTRAINT UK_BS_PARTICIPACAO UNIQUE (ocorrencia_id, resgatista_id),
                                         CONSTRAINT FK_BS_PARTICIPACAO_OCORR FOREIGN KEY (ocorrencia_id) REFERENCES BS_OCORRENCIA (id) ON DELETE CASCADE,
                                         CONSTRAINT FK_BS_PARTICIPACAO_RESG FOREIGN KEY (resgatista_id) REFERENCES BS_RESGATISTA (id)
);

-- Avisos lidos pelo app Mobile
CREATE TABLE BS_NOTIFICACAO (
                                id          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                usuario_id  NUMBER(19)         NOT NULL,
                                titulo      VARCHAR2(120 CHAR) NOT NULL,
                                mensagem    VARCHAR2(500 CHAR) NOT NULL,
                                lida        NUMBER(1) DEFAULT 0 NOT NULL,
                                criada_em   TIMESTAMP          NOT NULL,
                                CONSTRAINT PK_BS_NOTIFICACAO PRIMARY KEY (id),
                                CONSTRAINT FK_BS_NOTIFICACAO_USUARIO FOREIGN KEY (usuario_id) REFERENCES BS_USUARIO (id),
                                CONSTRAINT CK_BS_NOTIFICACAO_LIDA CHECK (lida IN (0, 1))
);

-- Auditoria de acessos e alterações em dados sensíveis
CREATE TABLE BS_AUDIT_LOG (
                              id           NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                              usuario_id   NUMBER(19),
                              acao         VARCHAR2(30 CHAR)  NOT NULL,
                              entidade     VARCHAR2(40 CHAR)  NOT NULL,
                              entidade_id  NUMBER(19),
                              detalhe      VARCHAR2(1000 CHAR),
                              criado_em    TIMESTAMP          NOT NULL,
                              CONSTRAINT PK_BS_AUDIT_LOG PRIMARY KEY (id),
                              CONSTRAINT FK_BS_AUDIT_USUARIO FOREIGN KEY (usuario_id) REFERENCES BS_USUARIO (id)
);

-- Índices nas FKs e nos filtros mais usados (o Oracle não indexa FK sozinho)
CREATE INDEX IX_BS_USUARIO_ORGAO ON BS_USUARIO (orgao_id);
CREATE INDEX IX_BS_ENDERECO_PESSOA ON BS_ENDERECO (pessoa_id);
CREATE INDEX IX_BS_ENDERECO_DISTRITO ON BS_ENDERECO (distrito_id);
CREATE INDEX IX_BS_PESSOA_END_ATUAL ON BS_PESSOA_VULNERAVEL (endereco_atual_id);
CREATE INDEX IX_BS_VINCULO_USUARIO ON BS_VINCULO_RESPONSAVEL (usuario_id);
CREATE INDEX IX_BS_ALERTA_STATUS ON BS_ALERTA (status);
CREATE INDEX IX_BS_AD_DISTRITO ON BS_ALERTA_DISTRITO (distrito_id);
CREATE INDEX IX_BS_SITUACAO_ALERTA_SIT ON BS_SITUACAO_ALERTA (alerta_id, situacao);
CREATE INDEX IX_BS_SITUACAO_PESSOA ON BS_SITUACAO_ALERTA (pessoa_id);
CREATE INDEX IX_BS_OCORRENCIA_FILA ON BS_OCORRENCIA (orgao_id, status);
CREATE INDEX IX_BS_HISTORICO_OCORR ON BS_HISTORICO_OCORRENCIA (ocorrencia_id);
CREATE INDEX IX_BS_PARTICIPACAO_RESG ON BS_PARTICIPACAO_RESGATE (resgatista_id);
CREATE INDEX IX_BS_NOTIFICACAO_USUARIO ON BS_NOTIFICACAO (usuario_id, lida);
CREATE INDEX IX_BS_AUDIT_ENTIDADE ON BS_AUDIT_LOG (entidade, entidade_id);